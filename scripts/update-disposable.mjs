// Vendors the disposable-email-domains blocklist (CC0 1.0) into
// src/disposable/data.ts, at the upstream commit given or the newest on
// main. Prints the commit it wrote, which the weekly Disposable domains
// workflow puts in its PR title.
//
//   node scripts/update-disposable.mjs [commit]
//
// Every line must be a lowercase hostname of two or more labels, and the
// list must hold at least MIN_DOMAINS of them, so a broken or truncated
// upstream file fails here rather than shipping.
import { writeFile } from 'node:fs/promises';

const REPO = 'disposable-email-domains/disposable-email-domains';
const FILE = 'disposable_email_blocklist.conf';
const OUT = new URL('../src/disposable/data.ts', import.meta.url);
const MIN_DOMAINS = 5000;
const HOSTNAME =
  /^(?:[a-z\d](?:[a-z\d-]{0,61}[a-z\d])?\.)+[a-z\d](?:[a-z\d-]{0,61}[a-z\d])?$/;

async function get(url, accept) {
  const headers = { accept };
  // Optional; CI passes one to stay clear of the unauthenticated rate limit.
  if (process.env.GH_TOKEN) {
    headers.authorization = `Bearer ${process.env.GH_TOKEN}`;
  }
  const response = await fetch(url, { headers });
  if (!response.ok) {
    throw new Error(`GET ${url}: ${response.status} ${response.statusText}`);
  }
  return response;
}

const ref = process.argv[2] ?? 'main';
const commit = await (
  await get(
    `https://api.github.com/repos/${REPO}/commits/${ref}`,
    'application/vnd.github+json',
  )
).json();
const text = await (
  await get(
    `https://raw.githubusercontent.com/${REPO}/${commit.sha}/${FILE}`,
    'text/plain',
  )
).text();

const domains = [
  ...new Set(
    text
      .split('\n')
      .map((line) => line.trim().toLowerCase())
      .filter((line) => line !== '' && !line.startsWith('#')),
  ),
].toSorted();
const invalid = domains.filter(
  (domain) => !HOSTNAME.test(domain) || domain.length > 253,
);
if (invalid.length > 0) {
  throw new Error(`Not hostnames: ${invalid.slice(0, 10).join(', ')}`);
}
if (domains.length < MIN_DOMAINS) {
  throw new Error(`Only ${domains.length} domains; expected ${MIN_DOMAINS}+`);
}

const date = commit.commit.committer.date.slice(0, 10);
await writeFile(
  OUT,
  `// Generated by scripts/update-disposable.mjs; don't edit it by hand.
// ${FILE} from github.com/${REPO}
// at ${commit.sha} (${date}), CC0 1.0.
// THIRD_PARTY_NOTICES.md attributes it.

/**
 * Every disposable domain, one per line: a string rather than an array, so
 * loading the module parses one literal and the set is built on first use.
 *
 * @internal
 */
export const blocklist: string = \`${domains.join('\n')}\`;
`,
);
process.stdout.write(`${commit.sha}\n`);
